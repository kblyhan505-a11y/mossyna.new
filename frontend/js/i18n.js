function mossynaGetLang() {
  return localStorage.getItem("mossyna_lang") || "tr";
}

function mossynaSetLang(lang) {
  localStorage.setItem("mossyna_lang", lang);
  mossynaApplyLanguage();
}

function mossynaT(key) {
  const lang = mossynaGetLang();
  return (MOSSYNA_I18N[lang] && MOSSYNA_I18N[lang][key]) || (MOSSYNA_I18N.tr[key]) || key;
}

function mossynaIsRtl(lang) {
  return MOSSYNA_RTL_LANGS.includes(lang);
}

function mossynaApplyLanguage() {
  const lang = mossynaGetLang();
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", mossynaIsRtl(lang) ? "rtl" : "ltr");
  document.body.classList.toggle("is-rtl", mossynaIsRtl(lang));

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = mossynaT(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", mossynaT(key));
  });

  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    el.setAttribute("title", mossynaT(key));
  });

  document.querySelectorAll(".lang-switch button").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  // Dinamik olarak render edilen içerikleri (ürün kartları vb.) yeniden çiz
  document.dispatchEvent(new CustomEvent("mossyna:languagechange", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  mossynaApplyLanguage();
  document.querySelectorAll(".lang-switch button").forEach(btn => {
    btn.addEventListener("click", () => mossynaSetLang(btn.getAttribute("data-lang")));
  });
});
